/**
 * Formats a Mastercam dropdown entry path cleanly (e.g. C:\Users\Public\Docume...\MILL 3 - AXIS VMC MM.mcam-mmd)
 */
export function formatMachineMenuPath(dir = DEFAULT_MACHINE_DIRECTORY, fileName = '') {
  const safeDir = String(dir || DEFAULT_MACHINE_DIRECTORY);
  const normalizedDir = safeDir.endsWith('\\') || safeDir.endsWith('/') ? safeDir : `${safeDir}\\`;
  if (!fileName) return normalizedDir;
  if (normalizedDir.length <= 24) return `${normalizedDir}${fileName}`;
  const prefix = normalizedDir.slice(0, 22);
  return `${prefix}...\\${fileName}`;
}

/**
 * Resolves any machine ID against catalog + optional custom/user-modified list.
 */
export function resolveMachineById(machineId, customMachines = []) {
  if (machineId === 'design') return DESIGN_MODE_MACHINE;
  const fromCustom = (Array.isArray(customMachines) ? customMachines : []).find((m) => m && m.id === machineId);
  const fromCatalog = MACHINE_DEFINITIONS_CATALOG.find((m) => m.id === machineId);
  if (fromCustom && fromCatalog) return { ...fromCatalog, ...fromCustom };
  if (fromCustom) return fromCustom;
  if (fromCatalog) return fromCatalog;
  return null;
}

/**
 * Maps a machine definition record to one of the supported post-processor controller dialects.
 */
export function deriveControllerDialect(machine) {
  if (machine?.controllerDialect) return machine.controllerDialect;
  const ctrl = String(machine?.controller || '').toLowerCase();
  const name = String(machine?.name || '').toLowerCase();
  if (ctrl.includes('haas') || name.includes('haas')) return 'Haas NGC (Next Gen Control)';
  if (ctrl.includes('siemens') || name.includes('siemens')) return 'Siemens Sinumerik 840D sl';
  if (ctrl.includes('heidenhain') || name.includes('dmu')) return 'Heidenhain TNC 640 (Klartext)';
  if (ctrl.includes('grbl')) return 'GRBL / OpenBuilds / Shapeoko';
  if (ctrl.includes('mach')) return 'Mach3 / Mach4 / LinuxCNC';
  return 'Fanuc 30i / 31i / 0i-MF';
}

// Pure helpers for Machine Definition Menu Management
export function addMenuItems(currentIds = [], idsToAdd = []) {
  const next = Array.isArray(currentIds) ? [...currentIds] : [];
  (Array.isArray(idsToAdd) ? idsToAdd : []).forEach((id) => {
    if (id && !next.includes(id)) next.push(id);
  });
  return next;
}

export function removeMenuItems(currentIds = [], idsToRemove = []) {
  const removeSet = new Set(Array.isArray(idsToRemove) ? idsToRemove : []);
  return (Array.isArray(currentIds) ? currentIds : []).filter((id) => !removeSet.has(id));
}

export function moveMenuItemUp(currentIds = [], targetId) {
  const list = [...(Array.isArray(currentIds) ? currentIds : [])];
  const idx = list.indexOf(targetId);
  if (idx <= 0) return list;
  [list[idx - 1], list[idx]] = [list[idx], list[idx - 1]];
  return list;
}

export function moveMenuItemDown(currentIds = [], targetId) {
  const list = [...(Array.isArray(currentIds) ? currentIds : [])];
  const idx = list.indexOf(targetId);
  if (idx < 0 || idx >= list.length - 1) return list;
  [list[idx], list[idx + 1]] = [list[idx + 1], list[idx]];
  return list;
}
